import type { Effect, EventDefinition, Stat } from '../domain/model';
import type { ChildMoneyOperation } from '../domain/childhood';
import { choice, event, stat, flag } from './authoring';

const coins = (operation: ChildMoneyOperation, amount = 1): Effect => ({
  kind: 'child-money',
  operation,
  amount,
});
const habit = (amount: number): Effect => ({ kind: 'habit', amount });
type Path = [text: string, hint: string, outcome: string, effects: Effect[]];
const p = (
  text: string,
  hint: string,
  outcome: string,
  changes: Partial<Record<Stat, number>>,
  ...extra: Effect[]
): Path => [
  text,
  hint,
  outcome,
  [...Object.entries(changes).map(([key, n]) => stat(key as Stat, n!)), ...extra],
];
function scene(
  id: string,
  age: number,
  title: string,
  text: string,
  paths: Path[],
): EventDefinition {
  return event(
    'realism-' + id,
    age < 6 ? 'childhood' : 'education',
    title,
    text,
    { minAge: age, maxAge: age },
    paths.map(([label, hint, outcome, effects], i) =>
      choice(['a', 'b', 'c', 'd'][i], label, hint, outcome, effects),
    ),
    { version: 12, decisionActor: age < 3 ? 'caregiver' : 'child', once: false, cooldown: 24 },
  );
}
