function scene(
  id: string,
  title: string,
  text: string,
  minAge: number,
  maxAge: number | undefined,
  choices: Choice[],
): EventDefinition {
  return event(
    id,
    'relationship',
    title,
    text,
    { minAge, ...(maxAge === undefined ? {} : { maxAge }) },
    choices,
    { version: 9, once: false, cooldown: 36 },
  );
}
